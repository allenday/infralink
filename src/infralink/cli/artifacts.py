"""Safe artifact writing and bounded artifact result helpers."""

from __future__ import annotations

import hashlib
import json
import os
import stat
from pathlib import Path, PurePath

from infralink.cli.actions import action
from infralink.cli.contracts import (
    Action,
    Artifact,
    Binding,
    Page,
)
from infralink.cli.errors import CliFailure, ErrorCode
from infralink.cli.pagination import page_items, production_cursor_codec


def artifact_usage(message: str) -> CliFailure:
    return CliFailure(
        code=ErrorCode.USAGE_ERROR,
        message=message,
        exit_code=2,
        fix="Provide an explicit safe relative --output directory",
        next_actions=[
            action("help", ["infralink", "help"], "Show command output options"),
        ],
    )


def require_output(output: Path | None) -> Path:
    if output is None:
        raise artifact_usage("An explicit output directory is required")
    if output.is_absolute() or output == Path(".") or any(part == ".." for part in output.parts):
        raise artifact_usage("Output must be an unambiguous relative directory")
    if not output.parts or any(part in ("", ".") for part in output.parts):
        raise artifact_usage("Output must be an unambiguous relative directory")
    return output


def _safe_relative_file(path: Path) -> None:
    pure = PurePath(path)
    if pure.is_absolute() or not pure.parts or any(part in ("", ".", "..") for part in pure.parts):
        raise artifact_usage("Generated artifact path is unsafe")


def artifact_metadata(
    output: Path,
    generated: list[tuple[Path, str, bytes]],
) -> list[Artifact]:
    """Describe generated bytes without touching the filesystem."""
    output = require_output(output)
    artifacts = []
    for relative, media_type, body in sorted(
        generated,
        key=lambda item: item[0].as_posix(),
    ):
        _safe_relative_file(relative)
        artifacts.append(
            Artifact(
                path=(output / relative).as_posix(),
                media_type=media_type,
                sha256=hashlib.sha256(body).hexdigest(),
            )
        )
    return artifacts


def _directory_flags() -> int:
    return os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW


def _open_directory(parent_fd: int, parts: tuple[str, ...], *, create: bool) -> int:
    """Open a directory chain without resolving any component by pathname."""
    current_fd = os.dup(parent_fd)
    try:
        for part in parts:
            try:
                child_fd = os.open(part, _directory_flags(), dir_fd=current_fd)
            except FileNotFoundError:
                if not create:
                    raise
                try:
                    os.mkdir(part, 0o755, dir_fd=current_fd)
                except FileExistsError:
                    pass
                child_fd = os.open(part, _directory_flags(), dir_fd=current_fd)
            os.close(current_fd)
            current_fd = child_fd
        return current_fd
    except OSError:
        os.close(current_fd)
        raise artifact_usage("Output must contain only real directories") from None


def _validate_target(parent_fd: int, filename: str) -> None:
    try:
        target = os.stat(filename, dir_fd=parent_fd, follow_symlinks=False)
    except FileNotFoundError:
        return
    if not stat.S_ISREG(target.st_mode):
        raise artifact_usage("Generated artifact target is unsafe")


def write_artifacts(
    output: Path,
    generated: list[tuple[Path, str, bytes]],
) -> list[Artifact]:
    """Write bytes using descriptor-relative traversal rooted at the current directory."""
    output = require_output(output)
    ordered = sorted(generated, key=lambda item: item[0].as_posix())
    for relative, _media_type, _body in ordered:
        _safe_relative_file(relative)

    root_fd = os.open(".", _directory_flags())
    try:
        for relative, _media_type, body in ordered:
            output_fd: int | None = None
            parent_fd: int | None = None
            temporary: str | None = None
            temporary_created = False
            try:
                output_fd = _open_directory(root_fd, output.parts, create=True)
                parent_fd = _open_directory(output_fd, relative.parts[:-1], create=True)
                _validate_target(parent_fd, relative.name)
                temporary = f".infralink-{relative.name}.tmp"
                descriptor = os.open(
                    temporary,
                    os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                    0o644,
                    dir_fd=parent_fd,
                )
                temporary_created = True
                with os.fdopen(descriptor, "wb") as artifact_file:
                    artifact_file.write(body)
                os.replace(
                    temporary,
                    relative.name,
                    src_dir_fd=parent_fd,
                    dst_dir_fd=parent_fd,
                )
            except OSError:
                if parent_fd is not None and temporary is not None and temporary_created:
                    try:
                        os.unlink(temporary, dir_fd=parent_fd)
                    except FileNotFoundError:
                        pass
                raise artifact_usage("Generated artifact target is unsafe") from None
            finally:
                if parent_fd is not None:
                    os.close(parent_fd)
                if output_fd is not None:
                    os.close(output_fd)
    finally:
        os.close(root_fd)
    return artifact_metadata(output, generated)


def artifact_fingerprint(
    *,
    command: str,
    sources: list[Path],
    options: dict[str, object],
    collections: dict[str, list[object]],
) -> str:
    source_digests = []
    for source in sources:
        try:
            digest = hashlib.sha256(source.read_bytes()).hexdigest()
        except OSError:
            digest = "unavailable"
        source_digests.append({"path": str(source), "sha256": digest})
    serialized = json.dumps(
        {
            "command": command,
            "sources": source_digests,
            "options": options,
            "collections": {
                name: [
                    item.model_dump(mode="json") if hasattr(item, "model_dump") else item
                    for item in items
                ]
                for name, items in collections.items()
            },
        },
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(serialized).hexdigest()


def artifact_pages(
    *,
    command: str,
    collections: dict[str, list[object]],
    selected: str,
    cursor: str | None,
    limit: int,
    fingerprint: str,
) -> dict[str, Page[object]]:
    if selected not in collections:
        from infralink.cli.pagination import invalid_cursor

        raise invalid_cursor()
    if cursor is not None and len(collections) > 1 and not selected:
        from infralink.cli.pagination import invalid_cursor

        raise invalid_cursor()
    offset = (
        production_cursor_codec().decode(cursor, command, selected, fingerprint)
        if cursor is not None
        else 0
    )
    pages: dict[str, Page[object]] = {}
    for name, items in collections.items():
        collection_offset = offset if name == selected else 0
        page = page_items(items, limit=limit, offset=collection_offset, next_cursor="pending")
        if page.page.next_cursor is not None:
            page.page.next_cursor = production_cursor_codec().encode(
                command,
                name,
                collection_offset + limit,
                fingerprint,
            )
        pages[name] = page
    return pages


def continuation_actions(
    *,
    base_argv: list[str],
    limit: int,
    pages: dict[str, Page[object]],
    sources: dict[str, str],
) -> list[Action]:
    actions: list[Action] = []
    for name, page in pages.items():
        if page.page.next_cursor is None:
            continue
        actions.append(
            action(
                "continue",
                [
                    *base_argv,
                    "--collection",
                    name,
                    "--cursor",
                    "{cursor}",
                    "--limit",
                    str(limit),
                ],
                f"Continue {name}",
                bindings={
                    "cursor": Binding(
                        type="string",
                        required=True,
                        source=sources[name],
                    )
                },
            )
        )
    return actions
